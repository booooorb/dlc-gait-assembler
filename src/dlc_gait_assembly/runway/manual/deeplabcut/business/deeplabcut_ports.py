"""Required project, command, environment, bridge, and artifact operations for DeepLabCut."""

from pathlib import Path
from typing import Protocol


class DeepLabCutProjectPort(Protocol):
    def validate_project(self, path: Path) -> Path: ...


class DeepLabCutBridgePort(Protocol):
    def request(
        self, request: dict, total_videos: int, phase: str, message: str, failure_label: str, progress_callback
    ) -> dict: ...
    def decode_result(self, item: dict): ...


class DeepLabCutArtifactPort(Protocol):
    def resolve(self, path: Path) -> Path: ...
    def analysis_folder(self, destination: Path, region: str) -> Path: ...
    def labeled_folder(self, destination: Path, region: str) -> Path: ...


class DeepLabCutEnvironmentPort(Protocol):
    def prepare(self, command: str, cwd: Path): ...
    def change_directory(self, command: str, cwd: Path) -> Path: ...
    def organize_outputs(self): ...
    def session(self): ...
