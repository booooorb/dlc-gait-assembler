"""Associate packaged example figures with maintained scientific explanations."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class FigureDefinition:
    source: str
    filename: str
    title: str
    purpose: str
    shows: str
    interpretation: str
    provenance: str
    asset_path: Path
    documentation_url: str


def gait_figure_catalog(preview_root: Path) -> tuple[FigureDefinition, ...]:
    """Describe every non-PCA/RF figure created by the ALMA and RustLab1 workflows."""
    alma_previews = preview_root / "alma" / "figures"
    rustlab_root = preview_root / "rustlab1"
    alma_docs = "https://github.com/sollan/alma"
    rustlab_docs = "https://github.com/rustlab1/DLC-Gait-Analysis"

    def alma(filename, title, purpose, shows, interpretation):
        return FigureDefinition(
            "ALMA",
            filename,
            title,
            purpose,
            shows,
            interpretation,
            "Generated by DLC Gait Assembler from ALMA's official treadmill demo parameter table (30 cm/s).",
            alma_previews / filename,
            alma_docs,
        )

    def rustlab(filename, title, purpose, shows, interpretation):
        return FigureDefinition(
            "RustLab1",
            filename,
            title,
            purpose,
            shows,
            interpretation,
            "Rendered at 2400 px from the official RustLab1 representative baseline and 3-days-post-injury runway sample outputs.",
            rustlab_root / filename,
            rustlab_docs,
        )

    figures = (
        alma(
            "1_ALMA_cycle_timing.svg",
            "Gait-cycle timing",
            "Summarizes how each detected stride is divided between stance and swing.",
            "Cycle, stance, and swing durations plus stance percentage, grouped by hindlimb when available.",
            "Use it to compare temporal balance between limbs and to spot unusually long or short cycles.",
        ),
        alma(
            "2_ALMA_spatiotemporal_profile.svg",
            "Spatiotemporal profile",
            "Provides a compact overview of stride geometry and swing performance.",
            "Stride length, step height, maximum swing velocity, and mean toe-to-iliac-crest distance.",
            "Shifts in box positions show systematic gait differences; wide boxes or distant points indicate cycle variability.",
        ),
        alma(
            "3_ALMA_joint_kinematics.svg",
            "Joint kinematics",
            "Compares the working range of the MTP, ankle, knee, and hip.",
            "Flexion, extension, and angular amplitude summaries for each joint.",
            "Amplitude reflects range of motion. Read flexion and extension together before interpreting a change in amplitude.",
        ),
        alma(
            "4_ALMA_cycle_trends.svg",
            "Parameters across cycles",
            "Shows whether key measurements remain stable through the recording.",
            "Stride length, step height, stance percentage, and knee amplitude in gait-cycle order.",
            "Gradual slopes can reveal drift or fatigue-like changes; isolated peaks are useful quality-control targets.",
        ),
        alma(
            "5_ALMA_parameter_heatmap.svg",
            "Standardized parameter heatmap",
            "Makes multi-parameter cycle patterns visible on one shared scale.",
            "All available ALMA parameters standardized as z-scores for every detected gait cycle; constant parameters are retained.",
            "Warm and cool cells mean above- and below-recording averages, not different physical units or absolute severity.",
        ),
        alma(
            "6_ALMA_parameter_correlation.svg",
            "Parameter correlation",
            "Highlights measurements that change together across gait cycles.",
            "A Spearman correlation matrix for varying parameters with at least three usable cycles.",
            "Values near +1 or -1 indicate strong monotonic relationships; correlation alone does not establish cause.",
        ),
        alma(
            "7_ALMA_variability.svg",
            "Stride variability",
            "Summarizes cycle-to-cycle consistency of endpoint trajectories.",
            "ALMA's x-, y-, and combined-plane variability measurements over multi-stride windows.",
            "Higher values indicate less repeatable trajectories, but should be checked against tracking quality and cycle count.",
        ),
        alma(
            "8_ALMA_drag_profile.svg",
            "Toe-drag profile",
            "Summarizes detected low-clearance portions of swing.",
            "Drag duration and drag percentage for each accepted gait cycle.",
            "Interpret it with the configured clearance and consecutive-frame thresholds, since those define a drag event.",
        ),
        rustlab(
            "1_PLOT_bar_all_videos.svg",
            "Tracking reliability by video",
            "Checks the amount of confident DLC tracking before gait measurements are interpreted.",
            "The proportion of samples meeting the likelihood criterion across the representative runway recordings.",
            "Lower bars identify recordings that may need marker review or stricter exclusion before group comparisons.",
        ),
        rustlab(
            "2_PLOT_Donut_Summary_Validation.svg",
            "Tracking validation summary",
            "Condenses accepted versus rejected tracking into a quick quality-control view.",
            "The valid and invalid portions of the official representative sample after likelihood validation.",
            "A smaller valid segment signals that downstream timing and position measurements need extra scrutiny.",
        ),
        rustlab(
            "3_1_PLOT_control_for_outliers_before.svg",
            "Coordinate QC — before filtering",
            "Exposes raw coordinate spread and obvious tracking outliers.",
            "Marker coordinates from the representative sample before likelihood-based filtering.",
            "Remote clusters or implausible ranges suggest mislabeled or occluded points that should not drive gait metrics.",
        ),
        rustlab(
            "3_2_PLOT_control_for_outliers_after.svg",
            "Coordinate QC — after filtering",
            "Shows the coordinate data retained for analysis after reliability filtering.",
            "The same marker-coordinate overview after low-confidence observations are removed.",
            "Compare this with the raw panel to confirm outliers were reduced without erasing the expected movement path.",
        ),
        rustlab(
            "4_1_PLOT_Overview_Distribution_X.svg",
            "X-coordinate distribution",
            "Checks horizontal tracking coverage and unexpected position clusters.",
            "Distributions of filtered x coordinates across tracked markers and recordings.",
            "Separated or unusually broad distributions can indicate view alignment differences, drift, or remaining outliers.",
        ),
        rustlab(
            "4_2_PLOT_Overview_Distribution_Y.svg",
            "Y-coordinate distribution",
            "Checks vertical tracking coverage and unexpected height clusters.",
            "Distributions of filtered y coordinates across tracked markers and recordings.",
            "Use view-specific coordinate direction when reading height; image y often increases downward.",
        ),
        rustlab(
            "5_PLOT_overview_steps.svg",
            "Normalized marker overview",
            "Provides a camera-normalized overview of the tracked runway movement.",
            "Representative marker trajectories and step structure after coordinate normalization.",
            "Look for coherent paths and repeated step shapes; discontinuities usually merit frame-level inspection.",
        ),
        rustlab(
            "6_1_PLOT_DOWN_Analysis_Speed_QC.svg",
            "Down-view paw-speed QC",
            "Supports the speed-based separation of stance and swing phases.",
            "Hindpaw speed, plus forepaw speed in Hindlimb + Forelimb mode, in the bottom camera view.",
            "Low-speed regions correspond to stance candidates and higher-speed regions to swing candidates; noisy transitions reduce segmentation confidence.",
        ),
        rustlab(
            "6_2_sync_plots.svg",
            "Gait-cycle synchronization",
            "Compares gait-cycle timing and, in the combined mode, diagonal fore–hind coordination.",
            "Cycle duration, stride length, stance/swing timing, and FL–BR and FR–BL asynchronous-phase fractions when forelimbs are enabled.",
            "Higher diagonal asynchronous-phase fractions mean the paired forepaw and hindpaw spend more analyzed frames in opposing phases.",
        ),
        rustlab(
            "7_1_PLOT_FIRST_OVERVIEW_VERTICAL_BARPLOT.svg",
            "Vertical-height summary",
            "Summarizes lateral-view marker height and movement across groups.",
            "Side-view hindlimb measures and, when enabled, forepaw, wrist, elbow, and shoulder height/excursion measures.",
            "Use the summary to locate group differences, then inspect the timecourse to see when they occur.",
        ),
        rustlab(
            "7.2_PLOT_SECOND_OVERVIEW_Vertical_TIMECOURSE.svg",
            "Vertical-height timecourse",
            "Shows how lateral marker heights evolve throughout each representative run.",
            "Gait-cycle-ordered vertical measures for hindlimb markers and optional forelimb markers.",
            "Repeated oscillations should align with steps; abrupt jumps often reflect tracking artifacts rather than gait.",
        ),
        rustlab(
            "8_1_PLOT_Horizontal_Analysis_QC.svg",
            "Paw-position QC",
            "Checks horizontal paw position before protraction and retraction are summarized.",
            "Hindpaw position relative to hip and optional forepaw position relative to shoulder.",
            "Consistent periodic excursions support the derived movement measures; discontinuities should be reviewed.",
        ),
        rustlab(
            "8.2_PLOT_Protraction_Retraction.svg",
            "Protraction/retraction summary",
            "Summarizes forward and backward hindlimb and optional forelimb excursion.",
            "Protraction, retraction, average, and median horizontal paw-position measures by side and limb.",
            "Read forward and backward excursions together to distinguish a translated step from a changed movement range.",
        ),
        rustlab(
            "8_3_PLOT_Protraction_Retraction_line.svg",
            "Protraction/retraction timecourse",
            "Shows the sequence underlying the horizontal excursion summary.",
            "Hindpaw and optional forepaw horizontal position across gait cycles.",
            "Peaks and troughs mark opposing excursion phases; irregular spacing can indicate variable stepping or tracking loss.",
        ),
        rustlab(
            "9_1_PLOT_DURATION_of_STEPE.svg",
            "Step duration",
            "Compares how long detected steps last.",
            "ALMA hindlimb cycle durations and optional RustLab1 forelimb stance-onset intervals.",
            "Interpret very short or long values alongside the paw-speed plot to rule out split or merged step events.",
        ),
        rustlab(
            "9_2_PLOT_Distance_covered_per_step.svg",
            "Distance per step",
            "Compares horizontal distance covered by each detected hindlimb step.",
            "Per-step movement distance from the down-view tracking coordinates.",
            "Lower distances can reflect shorter steps, but calibration, direction, and tracking quality should be checked first.",
        ),
        rustlab(
            "10_1_PLOT_selected_horizontal_Angle.svg",
            "Paw and forelimb-angle timecourse",
            "Shows side-view forelimb joint kinematics when forelimbs are included; bottom-center angles are excluded from exports.",
            "Bottom-center angles have been removed. Side-view elbow and wrist angles remain when forelimbs are enabled; historical previews may still show bottom angles.",
            "Smooth repeated changes are expected through stepping; abrupt angle flips usually indicate coordinate problems.",
        ),
        rustlab(
            "10_2_PLOT_horizontal_Angle_line.svg",
            "Paw and forelimb-angle summary",
            "Compares optional side-view forelimb joint angles across gait cycles. Bottom-center angles are retired.",
            "Mean, 95th-percentile, and 10th-percentile summaries for side-view forelimb joints. Bottom-center angle summaries are retired.",
            "Side-to-side or day-to-day shifts indicate changed orientation only after view alignment and tracking QC are confirmed.",
        ),
    )

    return tuple(figure for figure in figures if figure.filename != "7_ALMA_variability.svg")
