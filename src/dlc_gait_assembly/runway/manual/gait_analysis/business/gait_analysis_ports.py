"""Input tables, result storage, and rendering required by gait use cases."""

from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol


class GaitOutputPort(Protocol):
    def resolve_calibration(self, settings): ...

    def prepare(self, output_folder: Path) -> None: ...

    def read_table(self, path: Path, **options): ...

    def read_views(self, view_set, view_mappings=None): ...

    def write_table(self, table, path: Path, **options) -> None: ...

    def exists(self, path: Path) -> bool: ...

    def validate_outputs(self, paths, expected_rows=None) -> None: ...

    def write_text(self, path: Path, text: str) -> None: ...

    def render_alma(self, parameters, destination: Path, name: str): ...

    def render_rustlab1(self, raw, parameters, extracted, destination, settings, filtering, preprocessed): ...

    def render_stickplot(self, prepared, destination): ...

    def write_synchronized(self, calculation, view_set, destination): ...

    def get_fignums(self): ...

    def close(self, selection): ...


class GaitSettingsStorePort(Protocol):
    def read(self, path: Path): ...

    def write(self, path: Path, settings): ...


@dataclass(frozen=True)
class GaitAnalysisOperations:
    """Available gait use cases, assembled with the configured runtime at startup."""

    analyze_alma: Callable
    analyze_rustlab1: Callable

    settings: GaitSettingsStorePort
    inputs: "GaitInputInspectionPort"
    results: "GaitResultPreviewPort"
    defaults: object


class GaitInputInspectionPort(Protocol):
    def bodyparts(self, path: Path) -> list[str]: ...
    def csv_files(self, directory: Path) -> tuple[Path, ...]: ...
    def probe_video(self, path: Path): ...


class GaitResultPreviewPort(Protocol):
    def previewable_paths(self, paths) -> tuple[Path, ...]: ...
    def table_preview(self, path: Path, limit: int) -> tuple[list[str], list[list[str]]]: ...
    def svg_bytes(self, path: Path) -> bytes: ...
    def exists(self, path: Path) -> bool: ...
