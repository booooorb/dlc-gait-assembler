"""Edit knee markers, segment lengths, direction, confidence, and calibration settings."""

from __future__ import annotations

from PySide6.QtWidgets import (
    QCheckBox,
    QComboBox,
    QDoubleSpinBox,
    QGridLayout,
    QLabel,
    QLineEdit,
    QPushButton,
    QTabWidget,
    QWidget,
)

import dlc_gait_assembly.shared.client.theme.theme_application_state as theme
from dlc_gait_assembly.shared.client.qt_input_behaviors import set_tooltip
from dlc_gait_assembly.shared.client.qt_sliding_tabs import install_sliding_tab_bar


def length_spin() -> QDoubleSpinBox:
    spin = QDoubleSpinBox()
    spin.setRange(0.001, 1000.0)
    spin.setDecimals(3)
    spin.setValue(1.5)
    spin.setSuffix(" cm")
    return spin


def build_knee_settings(self, left_column):
    self.settings_tabs = QTabWidget()
    install_sliding_tab_bar(self.settings_tabs, theme.TOOL_3)
    self.settings_tabs.setObjectName("KneeCorrectionSettingsTabs")
    self.settings_tabs.setDocumentMode(True)
    self.settings_tabs.tabBar().setExpanding(True)
    self.settings_tabs.setMaximumHeight(225)
    calibration_page = QWidget()
    calibration_layout = QGridLayout(calibration_page)
    calibration_layout.setContentsMargins(8, 8, 8, 8)
    self.calibration_map_button = QPushButton("Import calibration map")
    self.calibration_map_label = QLabel("No calibration map selected")
    self.calibration_map_label.setObjectName("MutedLabel")
    calibration_layout.addWidget(self.calibration_map_button, 0, 0)
    calibration_layout.addWidget(self.calibration_map_label, 0, 1)
    self.hip_knee_length = length_spin()
    set_tooltip(self.hip_knee_length, 'Length from hip to knee in centimeters, used with the hip and ankle positions to reconstruct the knee.')
    self.knee_ankle_length = length_spin()
    set_tooltip(self.knee_ankle_length, 'Length from knee to ankle in centimeters, used to constrain the reconstructed knee position.')
    calibration_layout.addWidget(QLabel("Hip–knee length (femur)"), 1, 0)
    calibration_layout.addWidget(self.hip_knee_length, 1, 1)
    calibration_layout.addWidget(QLabel("Knee–ankle length (tibia/fibula)"), 2, 0)
    calibration_layout.addWidget(self.knee_ankle_length, 2, 1)
    self.settings_tabs.addTab(calibration_page, "Calibration")
    labels_page = QWidget()
    labels_layout = QGridLayout(labels_page)
    labels_layout.setContentsMargins(8, 8, 8, 8)
    self.knee_label_combo = QComboBox()
    set_tooltip(self.knee_label_combo, 'Tracked knee marker to correct. Automatic selection finds labels containing knee.')
    self.knee_label_combo.addItem("Auto-detect labels containing 'knee'", None)
    self.knee_label_combo.setEnabled(False)
    labels_layout.addWidget(QLabel("Existing knee label"), 0, 0)
    labels_layout.addWidget(self.knee_label_combo, 0, 1)
    self.generated_knee_label_edit = QLineEdit("knee")
    set_tooltip(self.generated_knee_label_edit, 'Name of the knee marker written when a new knee trajectory is generated.')
    labels_layout.addWidget(QLabel("Generated knee label"), 1, 0)
    labels_layout.addWidget(self.generated_knee_label_edit, 1, 1)
    self.hip_label_combo = QComboBox()
    set_tooltip(self.hip_label_combo, 'Tracked hip marker used as the upper endpoint of the reconstructed leg.')
    self.hip_label_combo.addItem("Auto-detect matching hip", None)
    self.hip_label_combo.setEnabled(False)
    labels_layout.addWidget(QLabel("Hip label"), 2, 0)
    labels_layout.addWidget(self.hip_label_combo, 2, 1)
    self.ankle_label_combo = QComboBox()
    set_tooltip(self.ankle_label_combo, 'Tracked ankle marker used as the lower endpoint of the reconstructed leg.')
    self.ankle_label_combo.addItem("Auto-detect matching ankle", None)
    self.ankle_label_combo.setEnabled(False)
    labels_layout.addWidget(QLabel("Ankle label"), 3, 0)
    labels_layout.addWidget(self.ankle_label_combo, 3, 1)
    self.knee_direction_combo = QComboBox()
    set_tooltip(self.knee_direction_combo, 'Choose which side of the hip–ankle line the knee bends toward. Auto uses the old knee and continuity between frames.')
    self.knee_direction_combo.addItem("Auto from old knee / continuity", "auto")
    self.knee_direction_combo.addItem("Manual side A", "positive")
    self.knee_direction_combo.addItem("Manual side B", "negative")
    labels_layout.addWidget(QLabel("Knee direction"), 4, 0)
    labels_layout.addWidget(self.knee_direction_combo, 4, 1)
    self.likelihood_threshold = QDoubleSpinBox()
    self.likelihood_threshold.setRange(0.0, 1.0)
    self.likelihood_threshold.setDecimals(2)
    self.likelihood_threshold.setSingleStep(0.05)
    self.likelihood_threshold.setValue(0.0)
    set_tooltip(self.likelihood_threshold, 'Below this value, finite hip/ankle points still produce an estimated knee carrying their lower likelihood. They are not promoted to full confidence.')
    labels_layout.addWidget(QLabel("Flag hip/ankle likelihood below"), 5, 0)
    labels_layout.addWidget(self.likelihood_threshold, 5, 1)
    self.settings_tabs.addTab(labels_page, "Label selection")
    recovery_page = QWidget()
    recovery_layout = QGridLayout(recovery_page)
    self.adapt_lengths_checkbox = QCheckBox("Adjust impossible geometry for this frame")
    set_tooltip(self.adapt_lengths_checkbox, 'Allow frame-specific segment length adjustments when the configured lengths cannot connect the hip and ankle. Adjusted frames receive reduced confidence.')
    self.adapt_lengths_checkbox.setChecked(True)
    recovery_layout.addWidget(self.adapt_lengths_checkbox, 0, 0, 1, 2)
    self.fallback_ratio_spin = QDoubleSpinBox()
    self.fallback_ratio_spin.setRange(0.05, 10.0)
    self.fallback_ratio_spin.setDecimals(3)
    self.fallback_ratio_spin.setSingleStep(0.01)
    self.fallback_ratio_spin.setValue(0.83)
    set_tooltip(self.fallback_ratio_spin, 'Femur length / tibia length used only when configured lengths cannot form a triangle. Adult wild-type mouse measurements give approximately 0.83 (Windahl et al., 1999, Table 1): https://www.jci.org/articles/view/6730 . This is a fallback prior; projected lengths vary with pose.')
    recovery_layout.addWidget(QLabel("Fallback femur/tibia ratio"), 1, 0)
    recovery_layout.addWidget(self.fallback_ratio_spin, 1, 1)
    self.adjusted_confidence_spin = QDoubleSpinBox()
    self.adjusted_confidence_spin.setRange(0.0, 1.0)
    self.adjusted_confidence_spin.setDecimals(2)
    self.adjusted_confidence_spin.setSingleStep(0.05)
    self.adjusted_confidence_spin.setValue(0.25)
    set_tooltip(self.adjusted_confidence_spin, 'Confidence ceiling for frames requiring changed geometric lengths. Their score is also limited by hip/ankle likelihood and the size of the adjustment; this ceiling is a heuristic, not a measured probability.')
    recovery_layout.addWidget(QLabel("Adjusted-frame confidence max"), 2, 0)
    recovery_layout.addWidget(self.adjusted_confidence_spin, 2, 1)
    self.fill_coordinates_checkbox = QCheckBox("Fill unresolved display coordinates (confidence 0)")
    self.fill_coordinates_checkbox.setChecked(True)
    set_tooltip(self.fill_coordinates_checkbox, 'Interpolate unresolved positions between finite knee anchors, or use the nearest anchor at recording edges. These display placeholders carry confidence zero. With no finite anchors, coordinates remain unavailable.')
    recovery_layout.addWidget(self.fill_coordinates_checkbox, 3, 0, 1, 2)
    self.settings_tabs.addTab(recovery_page, "Recovery")
    pairings_page = QWidget()
    pairings_layout = QGridLayout(pairings_page)
    pairings_description = QLabel("Assign an H5 and video to each CSV, or restore automatic filename matching.")
    pairings_description.setWordWrap(True)
    pairings_layout.addWidget(pairings_description, 0, 0, 1, 2)
    pairings_layout.addWidget(self.customize_pairings_button, 1, 0)
    pairings_layout.addWidget(self.reset_pairings_button, 1, 1)
    pairings_layout.setRowStretch(2, 1)
    self.settings_tabs.addTab(pairings_page, "File pairings")
    left_column.addWidget(self.settings_tabs)
